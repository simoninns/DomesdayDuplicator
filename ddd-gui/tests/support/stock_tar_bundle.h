// The golden bundle: the exact bytes tools/make-update-bundle.sh produced,
// running GNU tar 1.35 and minisign 0.12 over the payloads and manifest in
// update_fixtures.h.
//
// Everything else in the update tests reads archives this project's own writer
// produced, which proves the reader and the writer agree with each other and
// nothing more. The released artefact is made by stock tar, and this is the one
// fixture that says the reader reads *that*. Without it, a difference between
// the two — a magic string, a numeric field's terminator, the padding at the
// end — would not show up until a user downloaded a release and the application
// told them it was corrupt.
//
// Regenerating it, if the manifest fixture ever changes:
//
//   ./tools/make-update-bundle.sh --output
//   domesday-duplicator-update-1.4.0.dddfw
//       --version 1.4.0 --commit 0123abcd --channel development
//       --secret-key tools/keys/development.key
//       --created 2026-08-14T09:15:00Z --notes "<the release notes line>"
//       --firmware firmware.img --firmware-identity 0123abcd
//       --gateware gateware-app.rpd --gateware-identity 0123abcd
//       --gateware-interface-version 2 --minimum-register-map-version 2
//
// then base64 the file's content blocks. GNU tar pads its output to a
// 10,240-byte record by default and only the first 4,608 bytes of this one are
// anything but zeros, so the padding is not stored here — the test appends it,
// and checks both the minimum two-block ending and the full record the real
// file carries.

