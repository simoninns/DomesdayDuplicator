// What GNU tar's default blocking factor pads the file out to.
inline constexpr size_t kStockTarBundleRecordBytes = 10240;

// Decode the fixture and append `padding_bytes` of zeros — the end-of-archive
// blocks.
//
// A base64 decoder of its own, rather than the engine's: the engine's is an
// implementation detail of the signature reader, and a fixture that decoded
// itself with the code under test would be a fixture that agreed with a bug.
inline std::vector<uint8_t> StockTarBundle(size_t padding_bytes) {
  static constexpr std::string_view kAlphabet =
      "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

  std::vector<uint8_t> bytes;
  uint32_t accumulator = 0;
  int bits = 0;
  for (char character : kStockTarBundleBase64) {
    const size_t symbol = kAlphabet.find(character);
    if (symbol == std::string_view::npos) {
      continue;
    }
    accumulator = (accumulator << 6) | static_cast<uint32_t>(symbol);
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      bytes.push_back(static_cast<uint8_t>((accumulator >> bits) & 0xFF));
    }
  }

  bytes.resize(bytes.size() + padding_bytes, 0);
  return bytes;
}

